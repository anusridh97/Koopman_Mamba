def format_tool_call_example(example):
    """
    Format a ToolAlpaca example into our training format.

    Format:
        <func_schema> {function_definitions} <sep>
        <user> {user_query} <sep>
        <call> <func_name> {name} </func_name> <args> {args_json} </args> <sep>
        <result> {result} <sep>
        <assistant> {response} <eos>
    """
    parts = []

    # Function schema
    if 'Functions' in example and example['Functions']:
        funcs = example['Functions']
        if isinstance(funcs, str):
            try:
                funcs = json.loads(funcs)
            except (json.JSONDecodeError, TypeError):
                funcs = funcs
        parts.append(f"<func_schema> {json.dumps(funcs) if isinstance(funcs, (list, dict)) else str(funcs)} <sep>")

    # Conversation turns
    if 'Instances' in example and example['Instances']:
        instances = example['Instances']
        if isinstance(instances, str):
            try:
                instances = json.loads(instances)
            except (json.JSONDecodeError, TypeError):
                instances = [{'input': instances, 'output': ''}]
        if isinstance(instances, dict):
            instances = [instances]

        for inst in instances:
            if isinstance(inst, dict):
                user_input = inst.get('input', inst.get('query', ''))
                if user_input:
                    parts.append(f"<user> {user_input} <sep>")

                # Check for intermediate tool calls
                intermediate = inst.get('intermediate_steps', inst.get('tool_calls', []))
                if intermediate:
                    if isinstance(intermediate, str):
                        try:
                            intermediate = json.loads(intermediate)
                        except (json.JSONDecodeError, TypeError):
                            intermediate = []
                    if isinstance(intermediate, list):
                        for step in intermediate:
                            if isinstance(step, dict):
                                fname = step.get('tool', step.get('function', step.get('name', 'unknown')))
                                fargs = step.get('tool_input', step.get('arguments', step.get('args', {})))
                                fresult = step.get('observation', step.get('result', ''))
                                args_str = json.dumps(fargs) if isinstance(fargs, dict) else str(fargs)
                                parts.append(f"<call> <func_name> {fname} </func_name> <args> {args_str} </args> <sep>")
                                if fresult:
                                    parts.append(f"<result> {str(fresult)[:200]} <sep>")
                            elif isinstance(step, (list, tuple)) and len(step) >= 2:
                                parts.append(f"<call> <func_name> {step[0]} </func_name> <args> {json.dumps(step[1]) if isinstance(step[1], dict) else str(step[1])} </args> <sep>")
                                if len(step) > 2 and step[2]:
                                    parts.append(f"<result> {str(step[2])[:200]} <sep>")

                output = inst.get('output', inst.get('response', ''))
                if output:
                    parts.append(f"<assistant> {output} <eos>")

    return "\n".join(parts) if parts else None


class ToolCallDataset(Dataset):
    """Dataset for tool-call pretraining."""

    def __init__(self, tokenizer, examples, max_len=2048):
        self.tokenizer = tokenizer
        self.max_len = max_len
        self.data = []

        # Special token IDs
        self.call_id = tokenizer.token_to_id("<call>")
        self.assistant_id = tokenizer.token_to_id("<assistant>")
        self.sep_id = tokenizer.token_to_id("<sep>")
        self.eos_id = tokenizer.token_to_id("<eos>")
        self.func_schema_id = tokenizer.token_to_id("<func_schema>")
        self.user_id = tokenizer.token_to_id("<user>")
        self.pad_id = tokenizer.token_to_id("<pad>")
        self.bos_id = tokenizer.token_to_id("<bos>")

        skipped = 0
        for ex in tqdm(examples, desc="Tokenizing"):
            formatted = format_tool_call_example(ex)
            if formatted is None or len(formatted.strip()) < 20:
                skipped += 1
                continue

            encoded = tokenizer.encode(formatted)
            ids = encoded.ids

            if len(ids) < 10:
                skipped += 1
                continue

            # Truncate
            ids = [self.bos_id] + ids[:max_len - 2] + [self.eos_id]
            self.data.append(ids)

        print(f"  Prepared {len(self.data)} examples, skipped {skipped}")

    def __len__(self):
        return len(self.data)

    def __getitem__(self, idx):
        ids = self.data[idx]
        T = len(ids) - 1
        x = torch.tensor(ids[:-1], dtype=torch.long)
        y = torch.tensor(ids[1:], dtype=torch.long)

        # Loss mask: only on <call>, <assistant>, and their content tokens
        # (not on <func_schema> or <user> input — those are context)
        loss_mask = torch.zeros(T, dtype=torch.float32)
        prefix_mask = torch.ones(T, dtype=torch.float32)

        in_output = False
        for t in range(T):
            tok = x[t].item()
            if tok == self.call_id or tok == self.assistant_id:
                in_output = True
            elif tok == self.sep_id or tok == self.eos_id:
                if in_output:
                    loss_mask[t] = 1.0  # include the separator
                in_output = False
            elif tok == self.func_schema_id or tok == self.user_id:
                in_output = False

            if in_output:
                loss_mask[t] = 1.0

        return x, y, loss_mask, prefix_mask


def collate_fn(batch):
    """Pad and collate."""
    max_len = max(x.shape[0] for x, *_ in batch)
    B = len(batch)
    x_pad = torch.zeros(B, max_len, dtype=torch.long)
    y_pad = torch.zeros(B, max_len, dtype=torch.long)
    lm_pad = torch.zeros(B, max_len)
    pm_pad = torch.zeros(B, max_len)
    for i, (x, y, lm, pm) in enumerate(batch):
        T = x.shape[0]
        x_pad[i, :T] = x
        y_pad[i, :T] = y
        lm_pad[i, :T] = lm
        pm_pad[i, :T] = pm
    return x_pad, y_pad, lm_pad, pm_pad

"""## 12. Training Loop"""

def get_lr(step, warmup, total, max_lr, min_lr=1e-6):
    if step < warmup:
        return max_lr * step / max(warmup, 1)
    progress = (step - warmup) / max(total - warmup, 1)
    return min_lr + 0.5 * (max_lr - min_lr) * (1.0 + math.cos(math.pi * progress))


def train(model, train_ds, eval_ds, cfg: ModelConfig, device):
    """Main training loop with gradient accumulation and AMP."""
    optimizer = torch.optim.AdamW(
        model.parameters(), lr=cfg.lr, betas=(0.9, 0.95),
        weight_decay=cfg.weight_decay)

    use_amp = HAS_AMP and device.type == 'cuda'
    scaler = amp_scaler() if use_amp else None

    train_loader = DataLoader(
        train_ds, batch_size=cfg.batch_size, shuffle=True,
        collate_fn=collate_fn, drop_last=True, num_workers=2, pin_memory=True)

    eval_loader = DataLoader(
        eval_ds, batch_size=cfg.batch_size, shuffle=False,
        collate_fn=collate_fn, drop_last=True)

    logs = {'step': [], 'train_loss': [], 'eval_loss': [], 'eval_acc': [],
            'lr': [], 'throughput': []}
    step = 0
    best_eval_loss = float('inf')
    data_iter = iter(train_loader)
    t0 = time.time()
    tokens_processed = 0

    model.train()
    pbar = tqdm(total=cfg.n_steps, desc=f"Training {model.name}")

    while step < cfg.n_steps:
        optimizer.zero_grad(set_to_none=True)
        accum_loss = 0.0

        for _ in range(cfg.grad_accum):
            try:
                batch = next(data_iter)
            except StopIteration:
                data_iter = iter(train_loader)
                batch = next(data_iter)

            bx, by, blm, bpm = [t.to(device, non_blocking=True) for t in batch]
            tokens_processed += bx.numel()

            if use_amp:
                with amp_autocast():
                    logits, _ = model(bx, prefix_mask=bpm, loss_mask=blm)
                    loss_all = F.cross_entropy(
                        logits.reshape(-1, logits.size(-1)),
                        by.reshape(-1), reduction='none').reshape_as(by)
                    loss = (loss_all * blm).sum() / blm.sum().clamp(min=1.0)
                    loss = loss / cfg.grad_accum
                scaler.scale(loss).backward()
            else:
                logits, _ = model(bx, prefix_mask=bpm, loss_mask=blm)
                loss_all = F.cross_entropy(
                    logits.reshape(-1, logits.size(-1)),
                    by.reshape(-1), reduction='none').reshape_as(by)
                loss = (loss_all * blm).sum() / blm.sum().clamp(min=1.0)
                loss = loss / cfg.grad_accum
                loss.backward()

            accum_loss += loss.item()

        # LR schedule
        cur_lr = get_lr(step, cfg.warmup_steps, cfg.n_steps, cfg.lr)
        for pg in optimizer.param_groups:
            pg['lr'] = cur_lr

        if use_amp:
            scaler.unscale_(optimizer)
            nn.utils.clip_grad_norm_(model.parameters(), 1.0)
            scaler.step(optimizer)
            scaler.update()
        else:
            nn.utils.clip_grad_norm_(model.parameters(), 1.0)
            optimizer.step()

        # Eval
        if step % cfg.eval_every == 0 or step == cfg.n_steps - 1:
            model.eval()
            eval_loss_sum, eval_count = 0.0, 0
            eval_correct, eval_total = 0, 0
            with torch.no_grad():
                for ebatch in eval_loader:
                    ex, ey, elm, epm = [t.to(device) for t in ebatch]
                    if use_amp:
                        with amp_autocast():
                            elogits, _ = model(ex, prefix_mask=epm)
                    else:
                        elogits, _ = model(ex, prefix_mask=epm)

                    eloss = F.cross_entropy(
                        elogits.reshape(-1, elogits.size(-1)),
                        ey.reshape(-1), reduction='none').reshape_as(ey)
                    eval_loss_sum += (eloss * elm).sum().item()
                    eval_count += elm.sum().item()
                    preds = elogits.argmax(dim=-1)
                    eval_correct += ((preds == ey) * elm).sum().item()
                    eval_total += elm.sum().item()

            model.train()
            eval_loss = eval_loss_sum / max(eval_count, 1)
            eval_acc = eval_correct / max(eval_total, 1)
            elapsed = time.time() - t0
            throughput = tokens_processed / elapsed

            logs['step'].append(step)
            logs['train_loss'].append(accum_loss)
            logs['eval_loss'].append(eval_loss)
            logs['eval_acc'].append(eval_acc)
            logs['lr'].append(cur_lr)
            logs['throughput'].append(throughput)

            if eval_loss < best_eval_loss:
                best_eval_loss = eval_loss

            pbar.set_postfix({
                'loss': f'{accum_loss:.3f}',
                'eval': f'{eval_loss:.3f}',
                'acc': f'{eval_acc:.3f}',
                'tok/s': f'{throughput:.0f}',
                'lr': f'{cur_lr:.1e}'
            })

        step += 1
        pbar.update(1)

    pbar.close()
    return logs, best_eval_loss

"""## 13. Tool-Call Evaluation Metrics"""

def evaluate_tool_calling(model, eval_ds, tokenizer, device, n_samples=200):
    """
    Evaluate tool-calling capability.

    Metrics:
      - Function name accuracy (did it predict the right function?)
      - Argument accuracy (did it get the args right?)
      - Full call accuracy (both name + args correct)
    """
    model.eval()
    call_id = tokenizer.token_to_id("<call>")
    func_name_id = tokenizer.token_to_id("<func_name>")
    end_func_id = tokenizer.token_to_id("</func_name>")
    args_id = tokenizer.token_to_id("<args>")
    end_args_id = tokenizer.token_to_id("</args>")
    sep_id = tokenizer.token_to_id("<sep>")

    results = {
        'func_name_correct': 0,
        'args_correct': 0,
        'full_correct': 0,
        'total': 0,
        'generated_samples': [],
    }

    for idx in range(min(n_samples, len(eval_ds))):
        x, y, lm, pm = eval_ds[idx]
        x = x.unsqueeze(0).to(device)

        # Find the first <call> token position
        call_positions = (x[0] == call_id).nonzero(as_tuple=True)[0]
        if len(call_positions) == 0:
            continue

        # Use context up to just before the <call> token
        call_pos = call_positions[0].item()
        context = x[:, :call_pos + 1]  # include <call> token

        # Generate up to next <sep>
        generated = []
        with torch.no_grad():
            for _ in range(100):
                logits, _ = model(context, prefix_mask=torch.ones(context.shape[1], device=device))
                next_tok = logits[0, -1].argmax().item()
                generated.append(next_tok)
                if next_tok == sep_id or next_tok == tokenizer.token_to_id("<eos>"):
                    break
                context = torch.cat([context, torch.tensor([[next_tok]], device=device)], dim=1)

        # Extract ground truth call from y
        gt_call_tokens = y[call_pos:].tolist()
        gt_sep = gt_call_tokens.index(sep_id) if sep_id in gt_call_tokens else len(gt_call_tokens)
        gt_call = gt_call_tokens[:gt_sep]

        # Compare
        gen_str = tokenizer.decode(generated)
        gt_str = tokenizer.decode(gt_call)

        # Extract function names
        gen_func = _extract_between(gen_str, "<func_name>", "</func_name>")
        gt_func = _extract_between(gt_str, "<func_name>", "</func_name>")

        gen_args = _extract_between(gen_str, "<args>", "</args>")
        gt_args = _extract_between(gt_str, "<args>", "</args>")

        func_match = gen_func.strip() == gt_func.strip() if gen_func and gt_func else False
        args_match = gen_args.strip() == gt_args.strip() if gen_args and gt_args else False

        results['func_name_correct'] += int(func_match)
        results['args_correct'] += int(args_match)
        results['full_correct'] += int(func_match and args_match)
        results['total'] += 1

        if len(results['generated_samples']) < 5:
            results['generated_samples'].append({
                'gt': gt_str, 'gen': gen_str,
                'func_match': func_match, 'args_match': args_match
            })

    total = max(results['total'], 1)
    results['func_name_acc'] = results['func_name_correct'] / total
    results['args_acc'] = results['args_correct'] / total
    results['full_acc'] = results['full_correct'] / total

    return results


def _extract_between(text, start_tag, end_tag):
    """Extract text between two tags."""
    s = text.find(start_tag)
    if s == -1:
        return ""
    s += len(start_tag)
    e = text.find(end_tag, s)
    if e == -1:
        return text[s:]
    return text[s:e]

