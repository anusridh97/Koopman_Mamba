"""## 2. Triton Kernels"""

# ---------- Kernel 1: Fused RoPE + Cumulative Angle ----------
# Standard RoPE does 3 ops: cumsum(delta*omega) -> cos/sin -> rotate
# We fuse all three into one kernel. For sequence length T and head dim N,
# this eliminates 2 intermediate buffers and 2 kernel launches.

if HAS_TRITON:
    @triton.jit
    def _fused_rope_kernel(
        # Input: keys or queries, shape (B*H, T, N) row-major
        X_ptr, stride_xb, stride_xt, stride_xn,
        # Output: rotated, same shape
        OUT_ptr, stride_ob, stride_ot, stride_on,
        # Delta: (B*H, T) — step sizes
        DELTA_ptr, stride_db, stride_dt,
        # Omega: (N_half,) — base frequencies
        OMEGA_ptr,
        # Dimensions
        T: tl.constexpr, N_HALF: tl.constexpr,
        BLOCK_T: tl.constexpr, BLOCK_N: tl.constexpr,
    ):
        """Fused cumulative-angle RoPE rotation.

        For each (batch*head, n_half) pair:
          theta[t, n] = sum_{s=0}^{t} delta[s] * omega[n]
          out[t, 2n]   = x[t, 2n]*cos(theta) - x[t, 2n+1]*sin(theta)
          out[t, 2n+1] = x[t, 2n]*sin(theta) + x[t, 2n+1]*cos(theta)

        The cumulative sum over T is done via sequential scan within each
        program instance (T dimension). This is fine because the scan is
        over the time dimension within a single (batch, head, freq) slice,
        and we parallelize across batch*head and freq dimensions.
        """
        pid_b = tl.program_id(0)   # batch*head index
        pid_n = tl.program_id(1)   # frequency pair index (over N_HALF)

        n_off = pid_n * BLOCK_N + tl.arange(0, BLOCK_N)  # freq indices
        n_mask = n_off < N_HALF

        # Load omega for this freq block
        omega = tl.load(OMEGA_ptr + n_off, mask=n_mask, other=0.0)

        # Sequential scan over time for cumulative angle
        theta_acc = tl.zeros((BLOCK_N,), dtype=tl.float32)

        for t in range(T):
            # Load delta[b, t]
            delta = tl.load(DELTA_ptr + pid_b * stride_db + t * stride_dt)
            theta_acc += delta * omega

            cos_t = tl.cos(theta_acc)
            sin_t = tl.sin(theta_acc)

            # Load even/odd components
            x_even_ptr = X_ptr + pid_b * stride_xb + t * stride_xt + 2 * n_off * stride_xn
            x_odd_ptr = X_ptr + pid_b * stride_xb + t * stride_xt + (2 * n_off + 1) * stride_xn

            x_e = tl.load(x_even_ptr, mask=n_mask, other=0.0).to(tl.float32)
            x_o = tl.load(x_odd_ptr, mask=n_mask, other=0.0).to(tl.float32)

            # Rotate
            out_e = x_e * cos_t - x_o * sin_t
            out_o = x_e * sin_t + x_o * cos_t

            # Store
            o_even_ptr = OUT_ptr + pid_b * stride_ob + t * stride_ot + 2 * n_off * stride_on
            o_odd_ptr = OUT_ptr + pid_b * stride_ob + t * stride_ot + (2 * n_off + 1) * stride_on

            tl.store(o_even_ptr, out_e.to(tl.float16), mask=n_mask)
            tl.store(o_odd_ptr, out_o.to(tl.float16), mask=n_mask)


    def fused_rope(x, delta, omega):
        """
        Fused RoPE rotation.

        Args:
            x: (B, T, H, N) — input keys/queries (interleaved real/imag)
            delta: (B, T, H) — step sizes
            omega: (H, N_half) — base frequencies

        Returns:
            rotated: (B, T, H, N) — RoPE-rotated output
        """
        B, T, H, N = x.shape
        N_HALF = N // 2

        # Reshape to (B*H, T, N) for kernel
        x_flat = x.permute(0, 2, 1, 3).contiguous().reshape(B * H, T, N)
        delta_flat = delta.permute(0, 2, 1).contiguous().reshape(B * H, T)

        # Expand omega from (H, N_half) to (B*H, N_half) isn't needed;
        # each program indexes into omega by freq, omega is shared
        # But we need per-head omega. Tile it.
        omega_flat = omega.contiguous()  # (H, N_half)
        # We'll pass omega per-head by indexing pid_b % H... actually simpler
        # to just expand to (B*H, N_half) and index by pid_b
        omega_expanded = omega_flat.unsqueeze(0).expand(B, -1, -1).reshape(B * H, N_HALF)

        out_flat = torch.empty_like(x_flat)

        BLOCK_N = min(triton.next_power_of_2(N_HALF), 64)

        grid = (B * H, triton.cdiv(N_HALF, BLOCK_N))

        # We need omega per program — pass the expanded version and index by pid_b
        # Actually we need a 2D omega. Let's simplify: use a wrapper kernel.
        # For now, use the simpler approach: one kernel per (b*h), scan over T.
        # The parallelism is across B*H*ceil(N_HALF/BLOCK_N) programs.

        _fused_rope_kernel[grid](
            x_flat, x_flat.stride(0), x_flat.stride(1), x_flat.stride(2),
            out_flat, out_flat.stride(0), out_flat.stride(1), out_flat.stride(2),
            delta_flat, delta_flat.stride(0), delta_flat.stride(1),
            omega_expanded,  # each pid_b reads omega_expanded[pid_b, :]
            T=T, N_HALF=N_HALF, BLOCK_T=1, BLOCK_N=BLOCK_N,
        )

        return out_flat.reshape(B, H, T, N).permute(0, 2, 1, 3)


    # ---------- Kernel 2: Parallel Prefix Scan (Blelloch) ----------
    # Replaces the serial `for c in range(n_chunks)` inter-chunk propagation.
    # Each chunk state = decay * prev_state + chunk_contribution.
    # This is a linear recurrence: s[c] = a[c]*s[c-1] + b[c]
    # which is a prefix scan with the operator (a, b) ⊕ (a', b') = (a*a', a'*b + b').

    @triton.jit
    def _prefix_scan_kernel(
        # Decay per chunk: (B*H, n_chunks) — log-space
        LOG_DECAY_ptr, stride_lb, stride_lc,
        # Chunk contributions: (B*H, n_chunks, NP)
        CONTRIB_ptr, stride_cb, stride_cc, stride_cn,
        # Output states: (B*H, n_chunks, NP)
        OUT_ptr, stride_ob, stride_oc, stride_on,
        # Dimensions
        N_CHUNKS: tl.constexpr, NP: tl.constexpr,
        BLOCK_NP: tl.constexpr,
    ):
        """Inclusive prefix scan for linear recurrence s[c] = exp(d[c])*s[c-1] + b[c].

        Uses sequential scan within each (batch*head, state_block) program.
        Parallelism is across B*H and state dimension blocks.
        For typical n_chunks=16-64 the sequential scan is fast.
        """
        pid_b = tl.program_id(0)  # batch*head
        pid_s = tl.program_id(1)  # state block

        s_off = pid_s * BLOCK_NP + tl.arange(0, BLOCK_NP)
        s_mask = s_off < NP

        # Running state accumulator
        state = tl.zeros((BLOCK_NP,), dtype=tl.float32)

        for c in range(N_CHUNKS):
            # Load log_decay and contribution
            log_d = tl.load(LOG_DECAY_ptr + pid_b * stride_lb + c * stride_lc)
            decay = tl.exp(log_d)

            contrib = tl.load(
                CONTRIB_ptr + pid_b * stride_cb + c * stride_cc + s_off * stride_cn,
                mask=s_mask, other=0.0
            )

            state = decay * state + contrib

            # Store
            tl.store(
                OUT_ptr + pid_b * stride_ob + c * stride_oc + s_off * stride_on,
                state, mask=s_mask
            )


    def parallel_prefix_scan(log_decay, contributions):
        """
        Parallel prefix scan for inter-chunk state propagation.

        Args:
            log_decay: (B, H, n_chunks) — log of decay per chunk
            contributions: (B, H, n_chunks, NP) — chunk boundary states

        Returns:
            states: (B, H, n_chunks, NP) — cumulative states after each chunk
        """
        B, H, n_chunks, NP = contributions.shape

        log_decay_flat = log_decay.reshape(B * H, n_chunks).contiguous()
        contrib_flat = contributions.reshape(B * H, n_chunks, NP).contiguous()
        out_flat = torch.empty_like(contrib_flat)

        BLOCK_NP = min(triton.next_power_of_2(NP), 128)
        grid = (B * H, triton.cdiv(NP, BLOCK_NP))

        _prefix_scan_kernel[grid](
            log_decay_flat, log_decay_flat.stride(0), log_decay_flat.stride(1),
            contrib_flat, contrib_flat.stride(0), contrib_flat.stride(1), contrib_flat.stride(2),
            out_flat, out_flat.stride(0), out_flat.stride(1), out_flat.stride(2),
            N_CHUNKS=n_chunks, NP=NP, BLOCK_NP=BLOCK_NP,
        )

        return out_flat.reshape(B, H, n_chunks, NP)


    # ---------- Kernel 3: Fused CG Lift ----------
    # Fuses: extract real/imag -> power spectrum -> cross-freq -> harmonics -> linear proj
    # into a single kernel per (batch, time, head) element.

    @triton.jit
    def _fused_cg_lift_kernel(
        # Input k_rot: (B*T*H, N) interleaved
        K_ptr, stride_kb, stride_kn,
        # Cross-frequency index pairs (n_cross,) each
        CROSS_I_ptr, CROSS_J_ptr, CROSS_SCALE_ptr,
        # Harmonic indices (n_harm,)
        HARM_IDX_ptr,
        # Projection weight: (rank, D_feat)
        PROJ_ptr, stride_pr, stride_pf,
        # Output: (B*T*H, rank)
        OUT_ptr, stride_ob, stride_or,
        # Dims
        N_HALF: tl.constexpr,
        N_CROSS: tl.constexpr,
        N_HARM: tl.constexpr,
        D_FEAT: tl.constexpr,
        RANK: tl.constexpr,
        BLOCK_R: tl.constexpr,
    ):
        """Fused CG lift: extract invariant features + project to rank."""
        pid_b = tl.program_id(0)   # batch*time*head
        pid_r = tl.program_id(1)   # rank block

        r_off = pid_r * BLOCK_R + tl.arange(0, BLOCK_R)
        r_mask = r_off < RANK

        # We'll compute the dot product proj[r, :] · features[:] for each r
        # Features are computed on-the-fly from k_rot

        # Load all of k_rot for this element (N values)
        # Split into real/imag
        acc = tl.zeros((BLOCK_R,), dtype=tl.float32)

        # --- Tier 1: Power spectrum (N_HALF features at indices 0..N_HALF-1) ---
        for m in range(N_HALF):
            kr = tl.load(K_ptr + pid_b * stride_kb + (2 * m) * stride_kn).to(tl.float32)
            ki = tl.load(K_ptr + pid_b * stride_kb + (2 * m + 1) * stride_kn).to(tl.float32)
            feat = kr * kr + ki * ki  # power spectrum

            # proj[r, m] * feat
            w = tl.load(PROJ_ptr + r_off * stride_pr + m * stride_pf, mask=r_mask, other=0.0)
            acc += w * feat

        # --- Tier 2: Cross-frequency (N_CROSS features at indices N_HALF..N_HALF+N_CROSS-1) ---
        for c in range(N_CROSS):
            idx_i = tl.load(CROSS_I_ptr + c)
            idx_j = tl.load(CROSS_J_ptr + c)
            scale = tl.load(CROSS_SCALE_ptr + c)

            kr_i = tl.load(K_ptr + pid_b * stride_kb + (2 * idx_i) * stride_kn).to(tl.float32)
            ki_i = tl.load(K_ptr + pid_b * stride_kb + (2 * idx_i + 1) * stride_kn).to(tl.float32)
            kr_j = tl.load(K_ptr + pid_b * stride_kb + (2 * idx_j) * stride_kn).to(tl.float32)
            ki_j = tl.load(K_ptr + pid_b * stride_kb + (2 * idx_j + 1) * stride_kn).to(tl.float32)

            feat = (kr_i * kr_j + ki_i * ki_j) * scale
            feat_idx = N_HALF + c
            w = tl.load(PROJ_ptr + r_off * stride_pr + feat_idx * stride_pf, mask=r_mask, other=0.0)
            acc += w * feat

        # --- Tier 3: Harmonics (2*N_HARM features) ---
        for h in range(N_HARM):
            idx = tl.load(HARM_IDX_ptr + h)
            kr = tl.load(K_ptr + pid_b * stride_kb + (2 * idx) * stride_kn).to(tl.float32)
            ki = tl.load(K_ptr + pid_b * stride_kb + (2 * idx + 1) * stride_kn).to(tl.float32)

            feat_re = kr * kr - ki * ki
            feat_im = 2.0 * kr * ki

            feat_idx_re = N_HALF + N_CROSS + h
            feat_idx_im = N_HALF + N_CROSS + N_HARM + h

            w_re = tl.load(PROJ_ptr + r_off * stride_pr + feat_idx_re * stride_pf, mask=r_mask, other=0.0)
            w_im = tl.load(PROJ_ptr + r_off * stride_pr + feat_idx_im * stride_pf, mask=r_mask, other=0.0)
            acc += w_re * feat_re + w_im * feat_im

        # Store result
        tl.store(OUT_ptr + pid_b * stride_ob + r_off * stride_or, acc.to(tl.float16), mask=r_mask)

