"""## 5. Principled CG Lift"""

class PrincipledCGLift(nn.Module):
    """Cross-frequency slow invariants from RoPE group theory.
    v8 contribution — Tier 1/2/3 features + learned projection.
    Supports optional Triton-fused forward pass."""

    def __init__(self, N, rank, n_heads, max_cross=48, include_harmonics=True):
        super().__init__()
        self.N_half = N // 2
        self.rank = rank

        base_freq = 1.0 / (10000 ** (torch.arange(0, self.N_half).float() / self.N_half))

        # Slow cross-frequency pairs
        freq_diffs = []
        for i in range(self.N_half):
            for j in range(i + 1, self.N_half):
                diff = abs(base_freq[i].item() - base_freq[j].item())
                freq_diffs.append((diff, i, j))
        freq_diffs.sort(key=lambda x: x[0])
        n_cross = min(len(freq_diffs), max_cross)
        chosen = freq_diffs[:n_cross]

        self.register_buffer('cross_i',
            torch.tensor([p[1] for p in chosen]) if n_cross > 0 else torch.zeros(0, dtype=torch.long))
        self.register_buffer('cross_j',
            torch.tensor([p[2] for p in chosen]) if n_cross > 0 else torch.zeros(0, dtype=torch.long))

        # Low-frequency harmonics
        self.include_harmonics = include_harmonics
        if include_harmonics:
            median_freq = base_freq.median().item()
            self.register_buffer('harmonic_idx', torch.where(base_freq < median_freq)[0])
        else:
            self.register_buffer('harmonic_idx', torch.zeros(0, dtype=torch.long))

        n_harmonic = 2 * len(self.harmonic_idx)
        self.D_feat = self.N_half + n_cross + n_harmonic

        self.proj = nn.Linear(self.D_feat, rank, bias=False)
        nn.init.orthogonal_(self.proj.weight)

        if n_cross > 0:
            self.cross_scale = nn.Parameter(torch.ones(n_cross) * 0.5)
        else:
            self.cross_scale = None

    def forward(self, k_rot, use_triton_kernel=False):
        """k_rot: (B, T, H, N) interleaved. Returns (B, T, H, rank)."""
        # Triton fused path
        if use_triton_kernel and HAS_TRITON and k_rot.is_cuda:
            return self._forward_triton(k_rot)
        return self._forward_pytorch(k_rot)

    def _forward_pytorch(self, k_rot):
        kr = k_rot[..., 0::2]
        ki = k_rot[..., 1::2]
        feats = [kr ** 2 + ki ** 2]

        if len(self.cross_i) > 0:
            kr_i, kr_j = kr[..., self.cross_i], kr[..., self.cross_j]
            ki_i, ki_j = ki[..., self.cross_i], ki[..., self.cross_j]
            feats.append((kr_i * kr_j + ki_i * ki_j) * self.cross_scale)

        if self.include_harmonics and len(self.harmonic_idx) > 0:
            kr_h, ki_h = kr[..., self.harmonic_idx], ki[..., self.harmonic_idx]
            feats.append(kr_h ** 2 - ki_h ** 2)
            feats.append(2 * kr_h * ki_h)

        return self.proj(torch.cat(feats, dim=-1))

    def _forward_triton(self, k_rot):
        """Triton-fused CG lift."""
        B, T, H, N = k_rot.shape
        k_flat = k_rot.reshape(B * T * H, N).contiguous()
        out_flat = torch.empty(B * T * H, self.rank, device=k_rot.device, dtype=torch.float16)

        n_cross = len(self.cross_i)
        n_harm = len(self.harmonic_idx)
        BLOCK_R = min(triton.next_power_of_2(self.rank), 64)

        grid = (B * T * H, triton.cdiv(self.rank, BLOCK_R))

        cross_scale = self.cross_scale if self.cross_scale is not None else torch.zeros(1, device=k_rot.device)

        _fused_cg_lift_kernel[grid](
            k_flat, k_flat.stride(0), k_flat.stride(1),
            self.cross_i, self.cross_j, cross_scale,
            self.harmonic_idx,
            self.proj.weight, self.proj.weight.stride(0), self.proj.weight.stride(1),
            out_flat, out_flat.stride(0), out_flat.stride(1),
            N_HALF=self.N_half, N_CROSS=n_cross, N_HARM=n_harm,
            D_FEAT=self.D_feat, RANK=self.rank, BLOCK_R=BLOCK_R,
        )
        return out_flat.reshape(B, T, H, self.rank).to(k_rot.dtype)


class LegacyCGLift(nn.Module):
    """v7 CG lift — power spectrum + self-harmonics only."""
    def __init__(self, N, rank, use_harmonic=False):
        super().__init__()
        self.N_half = N // 2
        self.use_harmonic = use_harmonic
        D_feat = self.N_half if not use_harmonic else 3 * self.N_half
        self.proj = nn.Linear(D_feat, rank, bias=False)
        nn.init.orthogonal_(self.proj.weight)

    def forward(self, k_rot, use_triton_kernel=False):
        kr, ki = k_rot[..., 0::2], k_rot[..., 1::2]
        psi = kr ** 2 + ki ** 2
        if self.use_harmonic:
            psi = torch.cat([psi, kr ** 2 - ki ** 2, 2 * kr * ki], dim=-1)
        return self.proj(psi)

"""## 6. Recurrence — Chunked SSD with Triton Prefix Scan"""

def _segsum_lower_tri(log_alpha_chunk):
    C = log_alpha_chunk.shape[-1]
    cumsum = torch.cumsum(log_alpha_chunk, dim=-1)
    L_log = cumsum.unsqueeze(-1) - cumsum.unsqueeze(-2)
    mask = torch.tril(torch.ones(C, C, device=log_alpha_chunk.device, dtype=torch.bool))
    return torch.exp(L_log.masked_fill(~mask, -float('inf')))


def run_recurrence(k_real, k_imag, v, q_real, q_imag,
                   alpha, beta, gamma, chunk_size=64, use_triton=True):
    """Chunked SSD recurrence with optional Triton-accelerated prefix scan."""
    B, T, H, N_half = k_real.shape
    P = v.shape[-1]
    dev = v.device
    C = chunk_size

    # Precompute inputs
    U_real = k_real.unsqueeze(-1) * v.unsqueeze(-2)
    U_imag = k_imag.unsqueeze(-1) * v.unsqueeze(-2)
    U_real_prev = F.pad(U_real[:, :-1], (0, 0, 0, 0, 0, 0, 1, 0))
    U_imag_prev = F.pad(U_imag[:, :-1], (0, 0, 0, 0, 0, 0, 1, 0))
    beta_e = beta.unsqueeze(-1).unsqueeze(-1)
    gamma_e = gamma.unsqueeze(-1).unsqueeze(-1)
    b_real = (beta_e * U_real_prev + gamma_e * U_real).float()
    b_imag = (beta_e * U_imag_prev + gamma_e * U_imag).float()
    alpha_f32 = alpha.float()
    q_real_f32, q_imag_f32 = q_real.float(), q_imag.float()

    # Pad to chunk boundary
    T_orig = T
    if T % C != 0:
        pad_len = C - (T % C)
        b_real = F.pad(b_real, (0, 0, 0, 0, 0, 0, 0, pad_len))
        b_imag = F.pad(b_imag, (0, 0, 0, 0, 0, 0, 0, pad_len))
        alpha_f32 = F.pad(alpha_f32, (0, 0, 0, pad_len), value=1e-8)
        q_real_f32 = F.pad(q_real_f32, (0, 0, 0, 0, 0, pad_len))
        q_imag_f32 = F.pad(q_imag_f32, (0, 0, 0, 0, 0, pad_len))
        T = b_real.shape[1]

    n_chunks = T // C
    NP = N_half * P

    # Reshape into chunks
    b_re_c = b_real.reshape(B, n_chunks, C, H, N_half, P)
    b_im_c = b_imag.reshape(B, n_chunks, C, H, N_half, P)
    alpha_c = alpha_f32.reshape(B, n_chunks, C, H)
    log_alpha = torch.log(alpha_c.clamp(min=1e-8)).permute(0, 3, 1, 2)  # (B, H, n_chunks, C)

    b_re_bh = b_re_c.permute(0, 3, 1, 2, 4, 5).reshape(B, H, n_chunks, C, NP)
    b_im_bh = b_im_c.permute(0, 3, 1, 2, 4, 5).reshape(B, H, n_chunks, C, NP)

    # Intra-chunk: lower-triangular matmul
    L = _segsum_lower_tri(log_alpha)
    H_re_intra = torch.matmul(L, b_re_bh)
    H_im_intra = torch.matmul(L, b_im_bh)

    # Chunk boundary states
    chunk_states_re = H_re_intra[:, :, :, -1, :]  # (B, H, n_chunks, NP)
    chunk_states_im = H_im_intra[:, :, :, -1, :]
    chunk_decay_log = log_alpha.sum(dim=-1)  # (B, H, n_chunks)

    # Inter-chunk: prefix scan
    use_triton_scan = (use_triton and HAS_TRITON and dev.type == 'cuda'
                       and n_chunks > 1)

    if use_triton_scan:
        # Triton parallel prefix scan
        true_states_re = parallel_prefix_scan(chunk_decay_log, chunk_states_re)
        true_states_im = parallel_prefix_scan(chunk_decay_log, chunk_states_im)
    else:
        # PyTorch serial fallback
        true_states_re = torch.zeros(B, H, n_chunks, NP, device=dev, dtype=torch.float32)
        true_states_im = torch.zeros(B, H, n_chunks, NP, device=dev, dtype=torch.float32)
        prev_re = torch.zeros(B, H, NP, device=dev, dtype=torch.float32)
        prev_im = torch.zeros(B, H, NP, device=dev, dtype=torch.float32)
        for c in range(n_chunks):
            decay = torch.exp(chunk_decay_log[:, :, c]).unsqueeze(-1)
            prev_re = decay * prev_re + chunk_states_re[:, :, c]
            prev_im = decay * prev_im + chunk_states_im[:, :, c]
            true_states_re[:, :, c] = prev_re
            true_states_im[:, :, c] = prev_im

    # Combine intra + inter
    cumsum_within = torch.cumsum(log_alpha, dim=-1)
    decay_from_start = torch.exp(cumsum_within)
    init_states_re = F.pad(true_states_re[:, :, :-1], (0, 0, 1, 0))
    init_states_im = F.pad(true_states_im[:, :, :-1], (0, 0, 1, 0))
    H_re_off = decay_from_start.unsqueeze(-1) * init_states_re.unsqueeze(-2)
    H_im_off = decay_from_start.unsqueeze(-1) * init_states_im.unsqueeze(-2)

    H_re_full = (H_re_intra + H_re_off).reshape(B, H, n_chunks, C, N_half, P)
    H_im_full = (H_im_intra + H_im_off).reshape(B, H, n_chunks, C, N_half, P)
    H_re_full = H_re_full.permute(0, 2, 3, 1, 4, 5).reshape(B, T, H, N_half, P)
    H_im_full = H_im_full.permute(0, 2, 3, 1, 4, 5).reshape(B, T, H, N_half, P)

    y = (torch.einsum('bthn,bthnp->bthp', q_real_f32, H_re_full) +
         torch.einsum('bthn,bthnp->bthp', q_imag_f32, H_im_full))
    return y[:, :T_orig].to(v.dtype)

"""## 7. Mamba-3 Block"""

class Mamba3Block(nn.Module):
    def __init__(self, cfg: ModelConfig):
        super().__init__()
        self.cfg = cfg
        H, N, P, d = cfg.n_heads, cfg.d_state, cfg.d_head, cfg.d_model
        proj_size = H * N + H * N + H * P + H + H + H
        self.in_proj = nn.Linear(d, proj_size, bias=False)
        self.out_proj = nn.Linear(d, d, bias=False)
        self.norm = nn.LayerNorm(d)
        self.delta_bias = nn.Parameter(torch.zeros(H))
        self.a_bias = nn.Parameter(torch.log(torch.linspace(0.5, 2.0, H)))

        N_half = N // 2
        base_freq = 1.0 / (10000 ** (torch.arange(0, N_half).float() / N_half))
        self.register_buffer('omega_base', base_freq.unsqueeze(0).expand(H, -1))
        self.omega_scale = nn.Parameter(torch.ones(H, 1))
        self.conv1d = nn.Conv1d(d, d, kernel_size=4, padding=3, groups=d, bias=True)

    @property
    def omega(self):
        return self.omega_scale * self.omega_base

    def forward(self, x, return_aux=False):
        B, T, d = x.shape
        C = self.cfg
        H, N, P = C.n_heads, C.d_state, C.d_head
        residual = x
        x = self.norm(x)

        proj = self.in_proj(x)
        idx = 0
        b_raw = proj[..., idx:idx + H * N].reshape(B, T, H, N); idx += H * N
        c_raw = proj[..., idx:idx + H * N].reshape(B, T, H, N); idx += H * N
        v_flat = proj[..., idx:idx + H * P]; idx += H * P
        delta_raw = proj[..., idx:idx + H].reshape(B, T, H); idx += H
        a_raw = proj[..., idx:idx + H].reshape(B, T, H); idx += H
        lam_raw = proj[..., idx:idx + H].reshape(B, T, H); idx += H

        v_conv = self.conv1d(v_flat.transpose(1, 2))[..., :T].transpose(1, 2)
        v = F.silu(v_conv).reshape(B, T, H, P)

        delta = torch.clamp(F.softplus(delta_raw + self.delta_bias), C.delta_min, C.delta_max)
        a = F.softplus(a_raw + self.a_bias)
        alpha = torch.clamp(torch.exp(-a * delta), max=C.alpha_max)
        lam = torch.sigmoid(lam_raw)
        beta = (1.0 - lam) * delta * alpha
        gamma = lam * delta

        # RoPE rotation — use Triton fused kernel if available
        use_triton = C.use_triton and HAS_TRITON and x.is_cuda
        if use_triton and fused_rope is not None:
            k_rot = fused_rope(b_raw, delta, self.omega)
            q_rot = fused_rope(c_raw, delta, self.omega)
        else:
            theta = build_cumulative_angles_pt(delta, self.omega)
            k_rot = rope_rotate_pt(b_raw, theta)
            q_rot = rope_rotate_pt(c_raw, theta)

        y = run_recurrence(
            k_rot[..., 0::2], k_rot[..., 1::2], v,
            q_rot[..., 0::2], q_rot[..., 1::2],
            alpha, beta, gamma,
            chunk_size=C.chunk_size, use_triton=use_triton)

        y = self.out_proj(y.reshape(B, T, d))
        aux = None
        if return_aux:
            aux = {'k_rot': k_rot, 'q_rot': q_rot, 'v': v, 'alpha': alpha}
        return y + residual, aux

"""## 8. SKA Module"""

class SKAModule(nn.Module):
    """Spectral Koopman Attention — v8 with principled CG lift."""

    def __init__(self, N, P, rank=32, ridge_eps=1e-3, scale=1.5,
                 power_K=2, cg_mode='principled',
                 use_spectral_norm=True, use_seq_max_norm=True,
                 d_model=None, n_heads=None):
        super().__init__()
        self.rank = rank
        self.ridge_eps = ridge_eps
        self.power_K = power_K
        self.use_spectral_norm = use_spectral_norm
        self.use_seq_max_norm = use_seq_max_norm
        self.cg_mode = cg_mode

        if cg_mode == 'independent':
            assert d_model and n_heads
            H = n_heads
            self.ska_key_proj = nn.Linear(d_model, H * rank, bias=False)
            self.ska_query_proj = nn.Linear(d_model, H * rank, bias=False)
            self.ska_value_proj = nn.Linear(d_model, H * P, bias=False)
            nn.init.orthogonal_(self.ska_key_proj.weight)
            nn.init.orthogonal_(self.ska_query_proj.weight)
            self.cg_lift = None
        elif cg_mode == 'principled':
            self.cg_lift = PrincipledCGLift(N, rank, n_heads or 8)
        elif cg_mode == 'legacy':
            self.cg_lift = LegacyCGLift(N, rank, use_harmonic=True)
        else:
            raise ValueError(f"Unknown cg_mode: {cg_mode}")

        self.eta = nn.Parameter(torch.tensor(scale))
        self.ssn_gamma = nn.Parameter(torch.tensor(1.0))

    def forward(self, k_rot_or_h, q_rot_or_none, v_or_none, prefix_mask,
                use_triton_kernel=False):
        if self.cg_mode == 'independent':
            h = k_rot_or_h
            B, T, _ = h.shape
            H = self.ska_key_proj.out_features // self.rank
            P = self.ska_value_proj.out_features // H
            r = self.rank
            z = self.ska_key_proj(h).reshape(B, T, H, r)
            zq = self.ska_query_proj(h).reshape(B, T, H, r)
            v_ska = self.ska_value_proj(h).reshape(B, T, H, P)
        else:
            B, T, H, N = k_rot_or_h.shape
            P = v_or_none.shape[-1]
            r = self.rank
            z = self.cg_lift(k_rot_or_h, use_triton_kernel=use_triton_kernel)
            zq = self.cg_lift(q_rot_or_none, use_triton_kernel=use_triton_kernel)
            v_ska = v_or_none

        ska_mask = prefix_mask
        ctx = (torch.amp.autocast('cuda', enabled=False)
               if torch.cuda.is_available() else nullcontext())

        with ctx:
            z_f, v_f, zq_f = z.float(), v_ska.float(), zq.float()
            m = ska_mask.float().unsqueeze(-1).unsqueeze(-1)

            if self.use_seq_max_norm:
                z_norms = z_f.norm(dim=-1, keepdim=True)
                max_norm = z_norms.max(dim=1, keepdim=True)[0]
                z_f = z_f / (max_norm + 1e-6)
                zq_f = zq_f / (max_norm + 1e-6)

            z_m = z_f * m
            G = torch.einsum('bthr,bths->bhrs', z_m, z_m)
            m_lag = (ska_mask[:, :-1] * ska_mask[:, 1:]).float().unsqueeze(-1).unsqueeze(-1)
            M_cov = torch.einsum('bthr,bths->bhrs',
                                 z_f[:, 1:] * m_lag, z_f[:, :-1] * m_lag)
            C_v = torch.einsum('bthp,bthr->bhpr', v_f * m, z_f * m)

            G_tilde = G + self.ridge_eps * torch.eye(r, device=G.device, dtype=torch.float32)
            L = _robust_cholesky(G_tilde)

            Y = torch.linalg.solve_triangular(L, M_cov, upper=False)
            Aw_T = torch.linalg.solve_triangular(L, Y.transpose(-1, -2), upper=False)
            A_w = Aw_T.transpose(-1, -2)

            if self.use_spectral_norm:
                A_w, sigma = _spectral_normalize_power_iter(A_w)
                A_w = A_w * torch.clamp(self.ssn_gamma, min=1.0, max=1.5)

            B_v = torch.cholesky_solve(C_v.transpose(-1, -2), L).transpose(-1, -2)

            zq_perm = zq_f.permute(0, 2, 3, 1)
            w_q = torch.linalg.solve_triangular(L, zq_perm, upper=False)
            # Power filter
            w_f = w_q
            for _ in range(self.power_K - 1):
                w_f = A_w @ w_f
            w_f = A_w @ w_f
            z_f_out = L @ w_f
            y_hat = (B_v @ z_f_out).permute(0, 3, 1, 2)

        return self.eta * y_hat.to(z.dtype)

"""## 9. Full Model — Mamba-3 + SKA LM (~8M params)"""

class SwiGLUMLP(nn.Module):
    def __init__(self, d, expand=8 / 3):
        super().__init__()
        d_ff = ((int(d * expand) + 63) // 64) * 64
        self.norm = nn.LayerNorm(d)
        self.w1 = nn.Linear(d, d_ff, bias=False)
        self.w2 = nn.Linear(d, d_ff, bias=False)
        self.w3 = nn.Linear(d_ff, d, bias=False)

    def forward(self, x):
        h = self.norm(x)
        return x + self.w3(F.silu(self.w1(h)) * self.w2(h))


class Mamba3LM(nn.Module):
    """Baseline Mamba-3 language model."""
    def __init__(self, cfg: ModelConfig):
        super().__init__()
        self.cfg = cfg
        self.embed = nn.Embedding(cfg.vocab_size, cfg.d_model)
        self.blocks = nn.ModuleList([Mamba3Block(cfg) for _ in range(cfg.n_layers)])
        self.mlps = nn.ModuleList([SwiGLUMLP(cfg.d_model) for _ in range(cfg.n_layers)])
        self.norm_f = nn.LayerNorm(cfg.d_model)
        self.lm_head = nn.Linear(cfg.d_model, cfg.vocab_size, bias=False)
        # Weight tying
        self.lm_head.weight = self.embed.weight
        self.name = "Mamba-3"

    def forward(self, x, prefix_mask=None, loss_mask=None):
        h = self.embed(x)
        for blk, mlp in zip(self.blocks, self.mlps):
            h, _ = blk(h)
            h = mlp(h)
        return self.lm_head(self.norm_f(h)), {}


class Mamba3SKALM(nn.Module):
    """Mamba-3 + SKA language model."""
    def __init__(self, cfg: ModelConfig):
        super().__init__()
        self.cfg = cfg
        self.embed = nn.Embedding(cfg.vocab_size, cfg.d_model)
        self.blocks = nn.ModuleList([Mamba3Block(cfg) for _ in range(cfg.n_layers)])
        self.mlps = nn.ModuleList([SwiGLUMLP(cfg.d_model) for _ in range(cfg.n_layers)])
        self.ska_modules = nn.ModuleDict()
        self.ska_norms = nn.ModuleDict()

        for i in range(cfg.n_layers):
            if i in cfg.ska_layers:
                self.ska_modules[str(i)] = SKAModule(
                    N=cfg.d_state, P=cfg.d_head, rank=cfg.ska_rank,
                    ridge_eps=cfg.ska_ridge, scale=cfg.ska_scale,
                    power_K=cfg.power_K, cg_mode=cfg.cg_mode,
                    use_spectral_norm=cfg.ska_spectral_norm,
                    use_seq_max_norm=cfg.ska_seq_max_norm,
                    d_model=cfg.d_model, n_heads=cfg.n_heads)
                if cfg.cg_mode == 'independent':
                    self.ska_norms[str(i)] = nn.LayerNorm(cfg.d_model)

        self.norm_f = nn.LayerNorm(cfg.d_model)
        self.lm_head = nn.Linear(cfg.d_model, cfg.vocab_size, bias=False)
        self.embed.weight = self.lm_head.weight  # tie
        self.ska_proj = nn.Linear(cfg.d_model, cfg.d_model, bias=False)
        self.name = f"Mamba-3+SKA({cfg.cg_mode})"

    def forward(self, x, prefix_mask=None, loss_mask=None):
        h = self.embed(x)
        use_triton = self.cfg.use_triton and HAS_TRITON and x.is_cuda

        for i, (blk, mlp) in enumerate(zip(self.blocks, self.mlps)):
            has_ska = str(i) in self.ska_modules
            h, aux = blk(h, return_aux=(has_ska and self.cfg.cg_mode != 'independent'))

            if has_ska and prefix_mask is not None:
                ska_mod = self.ska_modules[str(i)]
                if self.cfg.cg_mode == 'independent':
                    h_normed = self.ska_norms[str(i)](h)
                    ska_out = ska_mod(h_normed, None, None, prefix_mask,
                                      use_triton_kernel=use_triton)
                else:
                    if aux is not None:
                        ska_out = ska_mod(aux['k_rot'], aux['q_rot'], aux['v'],
                                          prefix_mask, use_triton_kernel=use_triton)
                    else:
                        ska_out = None

                if ska_out is not None:
                    Bs, Ts, Hs, Ps = ska_out.shape
                    h = h + self.ska_proj(ska_out.reshape(Bs, Ts, self.cfg.d_model))

            h = mlp(h)
        return self.lm_head(self.norm_f(h)), {}

"""## 10. BPE Tokenizer (trained on tool-call data)"""

SPECIAL_TOKENS = [
    "<pad>", "<bos>", "<eos>",
    "<func_schema>", "<user>", "<call>", "<result>", "<assistant>",
    "<func_name>", "</func_name>", "<args>", "</args>",
    "<sep>",
]


def build_tokenizer(texts, vocab_size=8192, special_tokens=None):
    """Train a BPE tokenizer on the given texts using HuggingFace tokenizers."""
    from tokenizers import Tokenizer, models, trainers, pre_tokenizers, processors

    if special_tokens is None:
        special_tokens = SPECIAL_TOKENS

    tokenizer = Tokenizer(models.BPE())
    tokenizer.pre_tokenizer = pre_tokenizers.ByteLevel(add_prefix_space=False)

    trainer = trainers.BpeTrainer(
        vocab_size=vocab_size,
        special_tokens=special_tokens,
        min_frequency=2,
        show_progress=True,
    )

    # Train from iterator
    tokenizer.train_from_iterator(texts, trainer=trainer)
    tokenizer.post_processor = processors.ByteLevel(trim_offsets=False)

    return tokenizer

